library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity zcu106_hdmi_ctl is
  generic (
    G_CLK_HZ          : positive := 100_000_000;
    G_I2C_HZ          : positive := 100_000;
    G_RST_LOW_MS      : positive := 10;     -- si5324_rst_n low after power-up
    G_RST_WAIT_MS     : positive := 20;     -- reset release to first access
    G_RETRIES         : natural  := 3;      -- further attempts after a failure
    G_RETRY_PAUSE_MS  : positive := 100;
    G_LOCK_STABLE_MS  : positive := 50;     -- LOL low this long = locked
    G_LOCK_TIMEOUT_MS : positive := 2000;   -- no lock after the writes: retry
    G_STRETCH_MAX_MS  : positive := 10;     -- SCL held low by a slave: retry
    G_TX_EN_FIRST     : boolean  := true    -- DP159 OE high before its access
  );
  port (
    clk          : in  std_logic;
    rst          : in  std_logic;           -- synchronous, active high
    scl_i        : in  std_logic;
    scl_o        : out std_logic;
    scl_t        : out std_logic;
    sda_i        : in  std_logic;
    sda_o        : out std_logic;
    sda_t        : out std_logic;
    si5324_rst_n : out std_logic;
    si5324_lol   : in  std_logic;           -- asynchronous
    tx_en        : out std_logic;
    done         : out std_logic;
    err          : out std_logic;
    status       : out std_logic_vector(15 downto 0);
    diag         : out std_logic_vector(8 downto 0)
  );
end entity zcu106_hdmi_ctl;

architecture rtl of zcu106_hdmi_ctl is

  type t_op is (OP_WR, OP_RMW, OP_UPD, OP_CHK, OP_DLY);
  type t_rom_entry is record
    op   : t_op;
    dev  : std_logic_vector(7 downto 0);    -- 7-bit I2C address
    reg  : std_logic_vector(7 downto 0);
    mask : std_logic_vector(7 downto 0);
    val  : std_logic_vector(7 downto 0);    -- OP_DLY: milliseconds
  end record;
  type t_rom is array (natural range <>) of t_rom_entry;

  -- BEGIN si5324_regs.py --vhdl-rom
  -- generated by: si5324_regs.py --vhdl-rom (do not edit, --write-vhdl replaces it)
  constant C_ROM : t_rom(0 to 32) := (
    (OP_RMW, x"68", x"00", x"40", x"40"),  --  0 FREE_RUN=1
    (OP_RMW, x"68", x"03", x"10", x"10"),  --  1 SQ_ICAL=1
    (OP_WR , x"68", x"04", x"FF", x"12"),  --  2 AUTOSEL_REG=00 manual, HST_DEL
    (OP_WR , x"68", x"06", x"FF", x"0F"),  --  3 SFOUT2=001 (off), SFOUT1=111 (LVDS)
    (OP_RMW, x"68", x"0A", x"08", x"08"),  --  4 DSBL2_REG=1: CKOUT2 disabled
    (OP_RMW, x"68", x"0B", x"02", x"02"),  --  5 PD_CK2=1
    (OP_WR , x"68", x"13", x"FF", x"23"),  --  6 FOS/VALTIME, LOCKT=011 (13.3 ms)
    (OP_RMW, x"68", x"15", x"FF", x"FC"),  --  7 CKSEL_PIN=0, CK1_ACTV_PIN=0 (read, value ignored)
    (OP_RMW, x"68", x"89", x"01", x"01"),  --  8 FASTLOCK=1
    (OP_UPD, x"68", x"00", x"40", x"40"),  --  9 FREE_RUN=1 (reparent xtal)
    (OP_UPD, x"68", x"0B", x"03", x"01"),  -- 10 PD_CK1=1, PD_CK2=0 (xtal is the CKIN2 path)
    (OP_UPD, x"68", x"03", x"C0", x"40"),  -- 11 CKSEL_REG=01: CKIN2 (= xtal in free run)
    (OP_WR , x"68", x"00", x"FF", x"54"),  -- 12 SI5324_FREE_RUN_EN
    (OP_WR , x"68", x"02", x"FF", x"62"),  -- 13 BWSEL_REG=6
    (OP_WR , x"68", x"0B", x"FF", x"41"),  -- 14 SI5324_PD_CK1_DIS
    (OP_WR , x"68", x"19", x"FF", x"A0"),  -- 15 N1_HS=9
    (OP_WR , x"68", x"1F", x"FF", x"00"),  -- 16 NC1_LS=4 [19:16]
    (OP_WR , x"68", x"20", x"FF", x"00"),  -- 17 NC1_LS [15:8]
    (OP_WR , x"68", x"21", x"FF", x"03"),  -- 18 NC1_LS [7:0]
    (OP_WR , x"68", x"28", x"FF", x"E0"),  -- 19 N2_HS=11, N2_LS=32400 [19:16]
    (OP_WR , x"68", x"29", x"FF", x"7E"),  -- 20 N2_LS [15:8]
    (OP_WR , x"68", x"2A", x"FF", x"8F"),  -- 21 N2_LS [7:0]
    (OP_WR , x"68", x"2E", x"FF", x"00"),  -- 22 N32=7619 [18:16]
    (OP_WR , x"68", x"2F", x"FF", x"1D"),  -- 23 N32 [15:8]
    (OP_WR , x"68", x"30", x"FF", x"C2"),  -- 24 N32 [7:0]
    (OP_WR , x"68", x"88", x"FF", x"40"),  -- 25 ICAL=1: start calibration
    (OP_CHK, x"5E", x"00", x"FF", x"44"),  -- 26 ID 'D'
    (OP_CHK, x"5E", x"01", x"FF", x"50"),  -- 27 ID 'P'
    (OP_WR , x"5E", x"09", x"FF", x"06"),  -- 28 dp159_program
    (OP_WR , x"5E", x"0B", x"FF", x"80"),  -- 29 SLEW_CTL=10, TX_TERM_CTL=00
    (OP_WR , x"5E", x"0C", x"FF", x"48"),  -- 30 VSWING +14 %, HDMI_TWPST1=00
    (OP_WR , x"5E", x"0D", x"FF", x"00"),  -- 31
    (OP_WR , x"5E", x"0A", x"FF", x"35")   -- 32 redriver/retimer crossover 1.0 Gb/s
  );
  -- END si5324_regs.py --vhdl-rom

  constant C_MS_DIV     : positive := G_CLK_HZ / 1000;
  constant C_RETRY_WAIT : positive := G_RETRY_PAUSE_MS + G_RST_LOW_MS;

  function max(a, b : natural) return natural is
  begin
    if a > b then return a; else return b; end if;
  end function;
  constant C_WAIT_MAX : natural := max(max(C_RETRY_WAIT, G_RST_WAIT_MS), 255);

  -- ---------------------------------------------------------------- bit engine
  -- commands of i2c_bit_engine
  constant C_START  : std_logic_vector(1 downto 0) := "00";
  constant C_RSTART : std_logic_vector(1 downto 0) := "01";
  constant C_BYTE   : std_logic_vector(1 downto 0) := "10";
  constant C_STOP   : std_logic_vector(1 downto 0) := "11";
  signal e_rst     : std_logic := '1';
  signal e_go      : std_logic := '0';
  signal e_cmd     : std_logic_vector(1 downto 0) := C_STOP;
  signal e_txd     : std_logic_vector(8 downto 0) := (others => '1');
  signal e_rx      : std_logic_vector(8 downto 0);
  signal e_done    : std_logic;
  signal e_tmo     : std_logic;

  signal lol_m, lol_s : std_logic := '1';
  signal scl_m, scl_s, sda_m, sda_s : std_logic := '1';
  signal cause_r   : std_logic_vector(3 downto 0) := (others => '0');
  signal cstep_r   : std_logic_vector(2 downto 0) := (others => '0');

  -- ---------------------------------------------------------------- sequencer
  type t_mstate is (M_RESET, M_PWRUP, M_FETCH, M_DELAY, M_XFER, M_XWAIT, M_EVAL,
                    M_LOCK, M_DONE, M_FAIL, M_ERROR);
  signal m_state   : t_mstate := M_RESET;
  signal pc        : natural range 0 to C_ROM'length := 0;
  signal attempt   : natural range 0 to G_RETRIES := 0;
  signal x_read    : std_logic := '0';      -- transaction is a read
  signal x_step    : natural range 0 to 6 := 0;
  signal x_nack    : std_logic := '0';
  signal x_data    : std_logic_vector(7 downto 0) := (others => '0');
  signal x_rd      : std_logic_vector(7 downto 0) := (others => '0');
  signal pre       : natural range 0 to C_MS_DIV - 1 := 0;
  signal ms_tick   : std_logic := '0';
  signal wait_ms   : natural range 0 to C_WAIT_MAX := G_RST_LOW_MS;
  signal lock_cnt  : natural range 0 to G_LOCK_STABLE_MS + 1 := 0;
  signal lock_tmo  : natural range 0 to G_LOCK_TIMEOUT_MS := 0;
  signal rst_n_r   : std_logic := '0';
  signal tx_en_r   : std_logic := '0';
  signal done_r    : std_logic := '0';
  signal err_r     : std_logic := '0';

  function state_code(s : t_mstate) return std_logic_vector is
  begin
    return std_logic_vector(to_unsigned(t_mstate'pos(s), 4));
  end function;

begin

  assert C_ROM'length <= 255
    report "zcu106_hdmi_ctl: ROM too long for the status index" severity failure;

  scl_o <= '0';
  sda_o <= '0';
  si5324_rst_n <= rst_n_r;
  tx_en <= tx_en_r;
  done  <= done_r;
  err   <= err_r;
  status(7 downto 0)   <= std_logic_vector(to_unsigned(pc, 8));
  status(11 downto 8)  <= state_code(m_state);
  status(14 downto 12) <= std_logic_vector(to_unsigned(attempt mod 8, 3));
  status(15)           <= lol_s;
  diag                 <= cstep_r & sda_s & scl_s & cause_r;

  sync : process (clk)
  begin
    if rising_edge(clk) then
      lol_m <= si5324_lol;
      lol_s <= lol_m;
      scl_m <= scl_i;
      scl_s <= scl_m;
      sda_m <= sda_i;
      sda_s <= sda_m;
    end if;
  end process;

  -- ---------------------------------------------------------------- bit engine
  -- (firmware/common/mister/hdl/i2c_bit_engine.vhd), idle while the chips
  -- are held in reset
  e_rst <= '1' when rst = '1' or m_state = M_RESET else '0';

  engine : entity work.i2c_bit_engine
    generic map (
      G_CLK_HZ         => G_CLK_HZ,
      G_I2C_HZ         => G_I2C_HZ,
      G_STRETCH_MAX_MS => G_STRETCH_MAX_MS)
    port map (
      clk   => clk,
      rst   => e_rst,
      go    => e_go,
      cmd   => e_cmd,
      txd   => e_txd,
      rxd   => e_rx,
      done  => e_done,
      tmo   => e_tmo,
      scl_i => scl_i,
      scl_t => scl_t,
      sda_i => sda_i,
      sda_t => sda_t);

  -- ---------------------------------------------------------------- sequencer
  seq : process (clk)
    variable e   : t_rom_entry;
    variable nv  : std_logic_vector(7 downto 0);
  begin
    if rising_edge(clk) then
      e_go <= '0';
      -- millisecond tick, restarted with every new wait
      ms_tick <= '0';
      if pre = C_MS_DIV - 1 then
        pre     <= 0;
        ms_tick <= '1';
      else
        pre <= pre + 1;
      end if;

      if pc <= C_ROM'high then
        e := C_ROM(pc);
      else
        e := C_ROM(C_ROM'high);
      end if;

      if rst = '1' then
        m_state  <= M_RESET;
        wait_ms  <= G_RST_LOW_MS;
        pre      <= 0;
        ms_tick  <= '0';
        attempt  <= 0;
        pc       <= 0;
        rst_n_r  <= '0';
        tx_en_r  <= '0';
        done_r   <= '0';
        err_r    <= '0';
        cause_r  <= (others => '0');
        cstep_r  <= (others => '0');
      else
        case m_state is
          when M_RESET =>
            rst_n_r <= '0';
            tx_en_r <= '0';
            pc      <= 0;
            if ms_tick = '1' then
              if wait_ms <= 1 then
                m_state <= M_PWRUP;
                wait_ms <= G_RST_WAIT_MS;
                pre     <= 0;
                ms_tick <= '0';
              else
                wait_ms <= wait_ms - 1;
              end if;
            end if;

          when M_PWRUP =>
            rst_n_r <= '1';
            if G_TX_EN_FIRST then
              tx_en_r <= '1';
            end if;
            if ms_tick = '1' then
              if wait_ms <= 1 then
                m_state <= M_FETCH;
              else
                wait_ms <= wait_ms - 1;
              end if;
            end if;

          when M_FETCH =>
            if pc > C_ROM'high then
              m_state  <= M_LOCK;
              tx_en_r  <= '1';
              lock_cnt <= 0;
              lock_tmo <= 0;
              pre      <= 0;
              ms_tick  <= '0';
            else
              x_step <= 0;
              x_nack <= '0';
              case e.op is
                when OP_DLY =>
                  m_state <= M_DELAY;
                  wait_ms <= to_integer(unsigned(e.val));
                  pre     <= 0;
                  ms_tick <= '0';
                when OP_WR =>
                  m_state <= M_XFER;
                  x_read  <= '0';
                  x_data  <= e.val;
                when others =>
                  m_state <= M_XFER;
                  x_read  <= '1';
              end case;
            end if;

          when M_DELAY =>
            if wait_ms = 0 then
              pc      <= pc + 1;
              m_state <= M_FETCH;
            elsif ms_tick = '1' then
              wait_ms <= wait_ms - 1;
            end if;

          when M_XFER =>
            -- write: START, addr+W, reg, data, STOP
            -- read:  START, addr+W, reg, Sr, addr+R, data (NACK), STOP
            e_go    <= '1';
            e_cmd   <= C_BYTE;
            m_state <= M_XWAIT;
            if x_nack = '1' then
              e_cmd <= C_STOP;
            else
              case x_step is
                when 0 =>
                  e_cmd <= C_START;
                when 1 =>
                  e_txd <= e.dev(6 downto 0) & '0' & '1';
                when 2 =>
                  e_txd <= e.reg & '1';
                when 3 =>
                  if x_read = '1' then
                    e_cmd <= C_RSTART;
                  else
                    e_txd <= x_data & '1';
                  end if;
                when 4 =>
                  if x_read = '1' then
                    e_txd <= e.dev(6 downto 0) & '1' & '1';
                  else
                    e_cmd <= C_STOP;
                  end if;
                when 5 =>
                  e_txd <= x"FF" & '1';        -- read, master NACK
                when others =>
                  e_cmd <= C_STOP;
              end case;
            end if;

          when M_XWAIT =>
            if e_done = '1' then
              if e_tmo = '1' then
                m_state <= M_FAIL;
                cause_r <= "0001";
                cstep_r <= std_logic_vector(to_unsigned(x_step, 3));
              elsif e_cmd = C_STOP then
                if x_nack = '1' then
                  m_state <= M_FAIL;
                  cause_r <= "0010";
                elsif x_read = '1' then
                  m_state <= M_EVAL;
                else
                  pc      <= pc + 1;
                  m_state <= M_FETCH;
                end if;
              else
                m_state <= M_XFER;
                x_step  <= x_step + 1;
                if e_cmd = C_BYTE then
                  if x_read = '1' and x_step = 5 then
                    x_rd <= e_rx(8 downto 1);
                  elsif e_rx(0) /= '0' then
                    x_nack <= '1';             -- no ACK: STOP, then fail
                    cstep_r <= std_logic_vector(to_unsigned(x_step, 3));
                  end if;
                end if;
              end if;
            end if;

          when M_EVAL =>
            nv := (x_rd and not e.mask) or (e.val and e.mask);
            x_step <= 0;
            x_nack <= '0';
            if e.op = OP_CHK then
              if (x_rd and e.mask) = e.val then
                pc      <= pc + 1;
                m_state <= M_FETCH;
              else
                m_state <= M_FAIL;
                cause_r <= "0100";
              end if;
            elsif e.op = OP_UPD and nv = x_rd then
              pc      <= pc + 1;
              m_state <= M_FETCH;
            else
              x_read  <= '0';
              x_data  <= nv;
              m_state <= M_XFER;
            end if;

          when M_LOCK =>
            tx_en_r <= '1';
            if lol_s = '1' then
              lock_cnt <= 0;
            elsif ms_tick = '1' then
              if lock_cnt = G_LOCK_STABLE_MS then
                m_state <= M_DONE;
              else
                lock_cnt <= lock_cnt + 1;
              end if;
            end if;
            if ms_tick = '1' then
              if lock_tmo = G_LOCK_TIMEOUT_MS then
                m_state <= M_FAIL;
                cause_r <= "1000";
              else
                lock_tmo <= lock_tmo + 1;
              end if;
            end if;

          when M_DONE =>
            done_r <= '1';

          when M_FAIL =>
            if attempt = G_RETRIES then
              m_state <= M_ERROR;
            else
              attempt <= attempt + 1;
              m_state <= M_RESET;
              wait_ms <= C_RETRY_WAIT;
              pre     <= 0;
              ms_tick <= '0';
              rst_n_r <= '0';
              tx_en_r <= '0';
            end if;

          when M_ERROR =>
            err_r <= '1';
        end case;
      end if;
    end if;
  end process;

end architecture rtl;
