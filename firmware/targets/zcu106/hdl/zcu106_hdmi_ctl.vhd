-- Description:
--   Programs the two chips on the HDMI_CTL I2C bus of the ZCU106 right after
--   configuration, without any Linux driver, so that the GTH HDMI transmitter
--   path runs:
--     Si5324 (0x68, U108)  free run from its 114.285 MHz crystal (XA/XB, the
--                          CKIN2 path, divider N32), 148.5 MHz on CKOUT1
--                          (MGTREFCLK0 of quad 223), CKOUT2 off
--     DP159  (0x5E, U94)   ID check 'D','P', HDMI 1.4 settings (<= 3.4 Gb/s)
--   The register sequence is the one the Linux drivers write (clk-si5324.c
--   si5324_initialize, pll_reparent(xtal), clkout_set_rate; dp159.c), as the
--   ROM C_ROM generated by firmware/targets/zcu106/scripts/si5324_regs.py,
--   which also documents every entry; without the device reset RST_REG = 1
--   of si5324_initialize: the chip does not ACK that data byte (it resets
--   at once, the driver ignores the error), the RST pin pulse of step 1 is
--   the same reset.  Ops:
--     OP_WR   write val
--     OP_RMW  read, write (old and not mask) or (val and mask)
--     OP_UPD  the same, but only written when the value changes
--             (regmap_update_bits of the driver)
--     OP_CHK  read, (old and mask) must equal val
--     OP_DLY  wait val milliseconds
--   Reads are "START addr+W reg Sr addr+R data NACK STOP" (regmap I2C, SMBus
--   read byte data), writes "START addr+W reg data STOP".
--   Sequence:
--     1. si5324_rst_n low G_RST_LOW_MS, then high; wait G_RST_WAIT_MS
--        (G_TX_EN_FIRST: tx_en goes high together with si5324_rst_n)
--     2. the ROM: Si5324, then DP159
--     3. tx_en high (if not yet), wait until si5324_lol is low for
--        G_LOCK_STABLE_MS (at most G_LOCK_TIMEOUT_MS), then done = '1'
--   A NACK, a failed check, SCL held low longer than G_STRETCH_MAX_MS or no
--   lock in time fail the attempt: si5324_rst_n and tx_en low for
--   G_RETRY_PAUSE_MS + G_RST_LOW_MS, then the whole sequence again; after
--   G_RETRIES retries err = '1' (sticky, until rst).
--   tx_en (DP159 OE): with G_TX_EN_FIRST = true (default) high before the
--   DP159 is accessed, as in a Linux HDMI design that ran on the board
--   (GPIO default 1 from configuration on, Linux programs the DP159 after);
--   OE low is the power-down of the DP159.  G_TX_EN_FIRST = false raises it
--   only after the DP159 writes.
--   I2C: open drain, *_o constant '0', *_t = '1' releases the line (IOBUFs
--   outside).  Bus timing, clock stretching and the stuck-bus timeout are
--   the generic i2c_bit_engine (firmware/common/mister/hdl); this file is
--   only the board's sequence and register table.  Single master.
--   status: (7:0) ROM index, (11:8) state, (14:12) attempt, (15) LOL (sync).
--   diag:   (3:0) cause of the last failed attempt, one-hot: 0 SCL held low
--           (engine timeout), 1 NACK, 2 check (OP_CHK value), 3 no lock;
--           (4) SCL, (5) SDA as seen on the pins now (synchronized);
--           (8:6) step of the transaction that failed (0 START, 1 address,
--           2 register, 3 data or Sr, 4 address+R, 5 read data, 6 STOP).
--   Single clock domain; si5324_lol is synchronized here, scl_i/sda_i in the engine.
