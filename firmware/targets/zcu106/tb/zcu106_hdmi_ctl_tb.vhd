-- Description:
--   I2C bus with pull-ups, the DUT and a slave model of the Si5324 (0x68,
--   register file with reset values, RST_REG and ICAL self-clearing, no answer
--   while si5324_rst_n is low) and of the DP159 (0x5E, ID 'D','P' in
--   registers 0/1).  The model logs every completed register access as
--   (R/W, device, register, value) and the log of the last attempt (cleared
--   when si5324_rst_n rises) must equal C_EXPECT, the bus trace that
--   si5324_regs.py derives from the driver sequence.  LOL model: high until
--   3 ms after ICAL, then a 2 ms low glitch, 3 ms high, low for good.
--   Checks in every case:
--     - START/STOP only at byte boundaries (SDA changes while SCL is high
--       anywhere else), repeated START only after addr+W+reg, one data byte
--       per transaction, the DUT releases SDA in the bits the slave drives
--     - the DUT changes SDA >= T_SCL/8 away from every SCL edge (setup and
--       hold of data, START, Sr, STOP)
--     - SCL period within +-10 % of 1/G_I2C_HZ inside a byte, low time
--       >= 47 % (tLOW 4.7 us at 100 kHz), high time >= 40 % (tHIGH 4.0 us),
--       of a data bit half a period +-1.5 clocks (also the first bit after
--       clock stretching)
--     - si5324_rst_n low >= G_RST_LOW_MS after rst, first Si5324 access
--       >= G_RST_WAIT_MS after it rose, no Si5324 access within 20 ms after
--       RST_REG (driver delay; the sequence no longer writes RST_REG: the chip
--       does not ACK that data byte, the model neither, and the RST pin resets
--       the register file the same way)
--     - done only with LOL low for >= G_LOCK_STABLE_MS (the glitch must not
--       count), no bus activity after done or err
--     - tx_en: G_TX_EN_FIRST = true high at every DP159 access, false low at
--       every DP159 access and high only after the five DP159 writes
--   G_CASE:
--     normal       sequence once, done
--     nack_first   the Si5324 NACKs its first address byte: one retry, done
--     nack_always  the Si5324 never answers: err after G_RETRIES + 1 attempts
--     lol_stuck    LOL stays high: full sequence, lock timeout, err
--     bad_id       DP159 register 0 is not 'D': err, no DP159 write
--     stretch      the slave holds SCL low after every ACK bit: done
--     scl_stuck    SCL held low all the time: stretch timeout fails each
--                  attempt at its first command, err
--   Prints "zcu106_hdmi_ctl_tb <case>: PASS" or "... FAIL".
-------------------------------------------------------------------------------
-- Copyright (c) 2026 by OHRZ
