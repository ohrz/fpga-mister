library ieee;
use ieee.std_logic_1164.all;
use ieee.numeric_std.all;

entity zcu106_hdmi_ctl_tb is
  generic (
    G_CASE        : string   := "normal";
    G_CLK_HZ      : positive := 400_000;
    G_I2C_HZ      : positive := 20_000;
    G_TX_EN_FIRST : boolean  := true
  );
end entity zcu106_hdmi_ctl_tb;

architecture sim of zcu106_hdmi_ctl_tb is

  constant C_RST_LOW_MS  : positive := 10;
  constant C_RST_WAIT_MS : positive := 20;
  constant C_RETRIES     : natural  := 2;
  constant C_PAUSE_MS    : positive := 5;
  constant C_STABLE_MS   : positive := 10;
  constant C_TIMEOUT_MS  : positive := 60;
  constant C_STRETCH_MS  : positive := 2;
  constant C_RSTREG_MS   : positive := 20;    -- SI5324_RESET_DELAY_MS

  constant T_CLK  : time := 1 sec / G_CLK_HZ;
  constant T_SCL  : time := 1 sec / G_I2C_HZ;
  constant T_MS   : time := 1 ms;
  constant T_HOLD : time := T_SCL / 50;       -- slave output delay after SCL fall

  type t_expect_entry is record
    kind : character;
    dev  : std_logic_vector(7 downto 0);
    reg  : std_logic_vector(7 downto 0);
    val  : std_logic_vector(7 downto 0);
  end record;
  type t_expect is array (natural range <>) of t_expect_entry;

  -- BEGIN si5324_regs.py --vhdl-expect
  -- generated by: si5324_regs.py --vhdl-expect (do not edit, --write-vhdl replaces it)
  constant C_EXPECT : t_expect(0 to 40) := (
    ('R', x"68", x"00", x"14"),  --  0
    ('W', x"68", x"00", x"54"),  --  1
    ('R', x"68", x"03", x"05"),  --  2
    ('W', x"68", x"03", x"15"),  --  3
    ('W', x"68", x"04", x"12"),  --  4
    ('W', x"68", x"06", x"0F"),  --  5
    ('R', x"68", x"0A", x"00"),  --  6
    ('W', x"68", x"0A", x"08"),  --  7
    ('R', x"68", x"0B", x"40"),  --  8
    ('W', x"68", x"0B", x"42"),  --  9
    ('W', x"68", x"13", x"23"),  -- 10
    ('R', x"68", x"15", x"FF"),  -- 11
    ('W', x"68", x"15", x"FC"),  -- 12
    ('R', x"68", x"89", x"00"),  -- 13
    ('W', x"68", x"89", x"01"),  -- 14
    ('R', x"68", x"00", x"54"),  -- 15
    ('R', x"68", x"0B", x"42"),  -- 16
    ('W', x"68", x"0B", x"41"),  -- 17
    ('R', x"68", x"03", x"15"),  -- 18
    ('W', x"68", x"03", x"55"),  -- 19
    ('W', x"68", x"00", x"54"),  -- 20
    ('W', x"68", x"02", x"62"),  -- 21
    ('W', x"68", x"0B", x"41"),  -- 22
    ('W', x"68", x"19", x"A0"),  -- 23
    ('W', x"68", x"1F", x"00"),  -- 24
    ('W', x"68", x"20", x"00"),  -- 25
    ('W', x"68", x"21", x"03"),  -- 26
    ('W', x"68", x"28", x"E0"),  -- 27
    ('W', x"68", x"29", x"7E"),  -- 28
    ('W', x"68", x"2A", x"8F"),  -- 29
    ('W', x"68", x"2E", x"00"),  -- 30
    ('W', x"68", x"2F", x"1D"),  -- 31
    ('W', x"68", x"30", x"C2"),  -- 32
    ('W', x"68", x"88", x"40"),  -- 33
    ('R', x"5E", x"00", x"44"),  -- 34
    ('R', x"5E", x"01", x"50"),  -- 35
    ('W', x"5E", x"09", x"06"),  -- 36
    ('W', x"5E", x"0B", x"80"),  -- 37
    ('W', x"5E", x"0C", x"48"),  -- 38
    ('W', x"5E", x"0D", x"00"),  -- 39
    ('W', x"5E", x"0A", x"35")   -- 40
  );
  -- END si5324_regs.py --vhdl-expect

  -- Si5324 reset values (Si53xx reference manual) of the registers used
  type t_regs is array (0 to 255) of std_logic_vector(7 downto 0);
  function si_reset return t_regs is
    variable r : t_regs := (others => x"00");
  begin
    r(0) := x"14"; r(2) := x"42"; r(3) := x"05"; r(4) := x"92"; r(6) := x"2D";
    r(10) := x"00"; r(11) := x"40"; r(19) := x"2C"; r(21) := x"FF";
    r(136) := x"00"; r(137) := x"00";
    return r;
  end function;

  function is_case(s : string) return boolean is
  begin
    return G_CASE = s;
  end function;

  -- address phases the Si5324 does not acknowledge at the start
  function nack_init return natural is
  begin
    if is_case("nack_first") then
      return 1;
    end if;
    return 0;
  end function;

  signal clk     : std_logic := '0';
  signal rst     : std_logic := '1';
  signal running : boolean := true;

  signal scl_bus, sda_bus : std_logic;
  signal scl, sda         : std_logic;
  signal scl_t, sda_t, scl_o, sda_o : std_logic;
  signal slv_sda  : std_logic := 'Z';
  signal slv_scl  : std_logic := 'Z';
  signal stuck_scl : std_logic := 'Z';
  signal si_rst_n, lol, tx_en, done, err : std_logic;
  signal status   : std_logic_vector(15 downto 0);
  signal diag     : std_logic_vector(8 downto 0);

  -- shared between the model processes and the final check
  type t_log is array (0 to 255) of t_expect_entry;
  shared variable log_v     : t_log;
  shared variable log_n     : natural := 0;
  shared variable errors    : natural := 0;
  shared variable attempts  : natural := 0;
  shared variable dp_writes : natural := 0;       -- DP159 writes, this attempt
  shared variable dp_writes_all : natural := 0;   -- DP159 writes, all attempts
  shared variable periods   : natural := 0;       -- SCL periods measured
  shared variable starts    : natural := 0;       -- START conditions so far
  shared variable bus_busy  : boolean := false;   -- START seen, STOP not yet

  signal t_rst_rel   : time := 0 ns;   -- rst released
  signal t_rstn_rise : time := 0 ns;   -- si5324_rst_n rose
  signal t_rstreg    : time := -1 sec; -- RST_REG written
  signal t_ical      : time := 0 ns;   -- ICAL written
  signal ical_seen   : boolean := false;
  signal ical_ev     : boolean := false;
  signal rstreg_ev   : boolean := false;

  procedure fail(msg : string) is
  begin
    report "ERROR: " & msg severity error;
    errors := errors + 1;
  end procedure;

  function hex(v : std_logic_vector) return string is
    constant digits : string(1 to 16) := "0123456789ABCDEF";
    variable s : string(1 to 2);
    variable n : std_logic_vector(7 downto 0);
  begin
    n := v;
    s(1) := digits(to_integer(unsigned(n(7 downto 4))) + 1);
    s(2) := digits(to_integer(unsigned(n(3 downto 0))) + 1);
    return s;
  end function;

begin

  clk <= not clk after T_CLK / 2 when running else '0';

  -- open-drain bus with pull-ups
  scl_bus <= 'H';
  sda_bus <= 'H';
  scl_bus <= scl_o when scl_t = '0' else 'Z';
  sda_bus <= sda_o when sda_t = '0' else 'Z';
  scl_bus <= slv_scl;
  scl_bus <= stuck_scl;
  sda_bus <= slv_sda;
  scl <= to_x01(scl_bus);
  sda <= to_x01(sda_bus);

  dut : entity work.zcu106_hdmi_ctl
    generic map (
      G_CLK_HZ          => G_CLK_HZ,
      G_I2C_HZ          => G_I2C_HZ,
      G_RST_LOW_MS      => C_RST_LOW_MS,
      G_RST_WAIT_MS     => C_RST_WAIT_MS,
      G_RETRIES         => C_RETRIES,
      G_RETRY_PAUSE_MS  => C_PAUSE_MS,
      G_LOCK_STABLE_MS  => C_STABLE_MS,
      G_LOCK_TIMEOUT_MS => C_TIMEOUT_MS,
      G_STRETCH_MAX_MS  => C_STRETCH_MS,
      G_TX_EN_FIRST     => G_TX_EN_FIRST)
    port map (
      clk => clk, rst => rst,
      scl_i => scl, scl_o => scl_o, scl_t => scl_t,
      sda_i => sda, sda_o => sda_o, sda_t => sda_t,
      si5324_rst_n => si_rst_n, si5324_lol => lol,
      tx_en => tx_en, done => done, err => err, status => status, diag => diag);

  stuck_scl <= '0' when is_case("scl_stuck") else 'Z';

  -- ---------------------------------------------------------------- reset pin
  rstn_mon : process
  begin
    wait until rst = '0';
    if si_rst_n /= '0' then
      fail("si5324_rst_n not low at the end of rst");
    end if;
    loop
      wait until rising_edge(si_rst_n);
      if attempts = 0 and now - t_rst_rel < C_RST_LOW_MS * T_MS then
        fail("si5324_rst_n low only " & time'image(now - t_rst_rel));
      end if;
      attempts := attempts + 1;
      log_n := 0;
      dp_writes := 0;
      wait until falling_edge(si_rst_n);
    end loop;
  end process;

  t_rstn_rise <= now when rising_edge(si_rst_n);

  -- ---------------------------------------------------------------- LOL model
  lol_model : process (clk)
    variable dt : time;
  begin
    if rising_edge(clk) then
      if is_case("lol_stuck") or not ical_seen or si_rst_n = '0' then
        lol <= '1';
      else
        dt := now - t_ical;
        if dt < 3 ms then
          lol <= '1';
        elsif dt < 5 ms then
          lol <= '0';                       -- glitch, shorter than C_STABLE_MS
        elsif dt < 8 ms then
          lol <= '1';
        else
          lol <= '0';
        end if;
      end if;
    end if;
  end process;

  ical_flag : process (ical_ev, si_rst_n, rstreg_ev)
  begin
    if si_rst_n'event and si_rst_n = '0' then
      ical_seen <= false;
    elsif rstreg_ev'event then
      ical_seen <= false;
    elsif ical_ev'event then
      ical_seen <= true;
      t_ical    <= now;
    end if;
  end process;

  -- ---------------------------------------------------------------- slave
  slave : process (scl, sda, si_rst_n)
    type t_dev is (D_NONE, D_SI, D_DP);
    variable si_regs  : t_regs := si_reset;
    variable dp_regs  : t_regs := (0 => x"44", 1 => x"50", others => x"00");
    variable in_txn   : boolean := false;
    variable bitcnt   : natural := 0;          -- bits committed in this byte
    variable byteidx  : natural := 0;
    variable pend     : std_logic := '1';
    variable shreg    : std_logic_vector(7 downto 0);
    variable rw       : std_logic := '0';
    variable dev      : t_dev := D_NONE;
    variable devaddr  : std_logic_vector(7 downto 0);
    variable ptr      : natural := 0;
    variable acked    : boolean := false;     -- address acknowledged
    variable slave_bit : boolean := false;    -- the slave drives this bit
    variable tx_byte  : std_logic_vector(7 downto 0);
    variable nbytes   : natural := 0;         -- data bytes in the transaction
    variable sr_ok    : boolean := false;
    variable si_rst_byte : boolean := false;   -- this data byte set RST_REG: no ACK
    variable nack_cnt : natural := nack_init;
    variable pend_ok  : boolean := false;     -- SCL rose since the last START/STOP/fall
    variable t_rise, t_fall : time := 0 ns;
    variable t_prise  : time := 0 ns;
    variable val      : std_logic_vector(7 downto 0);

    procedure log_entry(k : character; d : std_logic_vector(7 downto 0);
                        r : natural; v : std_logic_vector(7 downto 0)) is
    begin
      if log_n <= log_v'high then
        log_v(log_n) := (k, d, std_logic_vector(to_unsigned(r, 8)), v);
        log_n := log_n + 1;
      end if;
    end procedure;
  begin
    -- the RST pin resets the register file as RST_REG does
    if si_rst_n'event and si_rst_n = '0' then
      si_regs := si_reset;
    end if;
    -- START / STOP: SDA changes while SCL is high
    if sda'event and scl = '1' and not scl'event then
      if bitcnt /= 0 then
        fail("SDA changed while SCL high inside a byte (bit " & integer'image(bitcnt) & ")");
      end if;
      slave_bit := false;
      pend_ok   := false;
      slv_sda <= 'Z';
      if sda = '0' then                        -- START
        if in_txn and not sr_ok then
          fail("repeated START not after addr+W+reg");
        end if;
        if done = '1' or err = '1' then
          fail("bus activity after done/err");
        end if;
        starts := starts + 1;
        bus_busy := true;
        in_txn  := true;
        bitcnt  := 0;
        byteidx := 0;
        acked   := false;
        sr_ok   := false;
      else                                     -- STOP
        if in_txn and acked and nbytes /= 1 then
          fail("transaction with " & integer'image(nbytes) & " data bytes");
        end if;
        in_txn := false;
        bus_busy := false;
        bitcnt := 0;
        dev    := D_NONE;
        acked  := false;
        sr_ok  := false;
      end if;
    end if;

    if scl'event and scl = '1' then
      -- low time, period inside a byte
      if in_txn and now - t_fall < (T_SCL * 47) / 100 then
        fail("SCL low time " & time'image(now - t_fall));
      end if;
      if in_txn and bitcnt >= 1 then
        periods := periods + 1;
        if now - t_prise > (T_SCL * 11) / 10 or now - t_prise < (T_SCL * 9) / 10 then
          fail("SCL period " & time'image(now - t_prise) & ", expected " & time'image(T_SCL));
        end if;
      end if;
      t_prise := now;
      t_rise  := now;
      pend    := sda;
      pend_ok := true;
      if slave_bit and sda_t /= '1' then
        fail("DUT drives SDA in a bit of the slave");
      end if;
    end if;

    if scl'event and scl = '0' then
      if in_txn and now - t_rise < (T_SCL * 4) / 10 then
        fail("SCL high time " & time'image(now - t_rise));
      end if;
      -- data bit: two quarters high (+-1.5 clocks), also after stretching
      if in_txn and pend_ok and (now - t_rise > T_SCL / 2 + (3 * T_CLK) / 2 or
                                 now - t_rise < T_SCL / 2 - (3 * T_CLK) / 2) then
        fail("SCL high time of a bit " & time'image(now - t_rise) & ", expected " & time'image(T_SCL / 2));
      end if;
      t_fall := now;
      if in_txn and pend_ok then
        pend_ok := false;
        bitcnt := bitcnt + 1;
        if bitcnt <= 8 then
          shreg := shreg(6 downto 0) & pend;
        end if;
        slave_bit := false;
        slv_sda <= 'Z' after T_HOLD;

        if bitcnt = 8 then
          -- byte complete, the next bit is the ACK
          if byteidx = 0 then
            devaddr := '0' & shreg(7 downto 1);
            rw      := shreg(0);
            nbytes  := 0;
            if rw = '0' then
              dev := D_NONE;
            end if;
            if devaddr = x"68" then
              if si_rst_n /= '1' then
                null;                          -- in reset: no answer
              elsif is_case("nack_always") then
                null;
              elsif nack_cnt > 0 then
                nack_cnt := nack_cnt - 1;
              else
                dev := D_SI;
              end if;
              if now - t_rstn_rise < C_RST_WAIT_MS * T_MS then
                fail("Si5324 accessed " & time'image(now - t_rstn_rise) & " after reset release");
              end if;
              if now - t_rstreg < C_RSTREG_MS * T_MS then
                fail("Si5324 accessed " & time'image(now - t_rstreg) & " after RST_REG");
              end if;
            elsif devaddr = x"5E" then
              dev := D_DP;
              if G_TX_EN_FIRST and tx_en /= '1' then
                fail("DP159 accessed with tx_en low");
              end if;
              if not G_TX_EN_FIRST and tx_en /= '0' then
                fail("DP159 accessed with tx_en already high");
              end if;
            else
              fail("unknown device address 0x" & hex(devaddr));
              dev := D_NONE;
            end if;
            acked := dev /= D_NONE;
            if acked then
              slv_sda   <= '0' after T_HOLD;
              slave_bit := true;
            end if;
          elsif rw = '0' and acked then
            if byteidx = 1 then
              ptr   := to_integer(unsigned(shreg));
              sr_ok := true;
            else
              sr_ok  := false;
              si_rst_byte := false;
              nbytes := nbytes + 1;
              log_entry('W', devaddr, ptr, shreg);
              if dev = D_SI then
                si_regs(ptr) := shreg;
                if ptr = 136 and shreg(7) = '1' then
                  si_rst_byte := true;
                  si_regs   := si_reset;
                  t_rstreg  <= now;
                  rstreg_ev <= not rstreg_ev;
                elsif ptr = 136 and shreg(6) = '1' then
                  si_regs(136)(6) := '0';
                  ical_ev <= not ical_ev;
                end if;
              else
                dp_regs(ptr) := shreg;
                dp_writes := dp_writes + 1;
                dp_writes_all := dp_writes_all + 1;
              end if;
              ptr := (ptr + 1) mod 256;
            end if;
            -- the Si5324 resets itself on the data byte of RST_REG = 1 and gives no
            -- ACK for it (ZCU106, 2026-11-07: NACK at that byte, read before ACKed)
            if not (dev = D_SI and byteidx /= 1 and si_rst_byte) then
              slv_sda   <= '0' after T_HOLD;
              slave_bit := true;
            end if;
          elsif rw = '1' and acked then
            null;                              -- master ACK/NACK follows
          end if;
        elsif bitcnt = 9 then
          -- ACK bit done
          bitcnt  := 0;
          byteidx := byteidx + 1;
          if is_case("stretch") then
            slv_scl <= '0', 'Z' after 3 * T_SCL;
          end if;
          if rw = '1' and acked and (byteidx = 1 or pend = '0') then
            -- send a byte: after the address ACK or a master ACK
            if dev = D_SI then
              val := si_regs(ptr);
            else
              val := dp_regs(ptr);
              if is_case("bad_id") and ptr = 0 then
                val := x"58";
              end if;
            end if;
            log_entry('R', devaddr, ptr, val);
            nbytes  := nbytes + 1;
            tx_byte := val;
            ptr     := (ptr + 1) mod 256;
            slave_bit := true;
            if tx_byte(7) = '1' then
              slv_sda <= 'Z' after T_HOLD;
            else
              slv_sda <= '0' after T_HOLD;
            end if;
          end if;
        elsif rw = '1' and acked and byteidx >= 1 then
          -- next data bit of the slave (bits 6..0)
          slave_bit := true;
          if tx_byte(8 - bitcnt - 1) = '1' then
            slv_sda <= 'Z' after T_HOLD;
          else
            slv_sda <= '0' after T_HOLD;
          end if;
        end if;
      end if;
    end if;
  end process;

  -- ---------------------------------------------------------------- SDA setup/hold
  -- The DUT changes SDA (sda_t) at least T_SCL/8 away from every SCL edge:
  -- data hold after SCL falls, data setup before SCL rises, START/Sr/STOP
  -- setup and hold.
  sda_timing : process
    variable t_sclev, t_sdaev : time := 0 ns;
  begin
    wait on scl, sda_t;
    if rst = '0' and not is_case("scl_stuck") then
      if scl'event then
        if now - t_sdaev < T_SCL / 8 then
          fail("SCL edge " & time'image(now - t_sdaev) & " after an SDA change");
        end if;
        t_sclev := now;
      end if;
      if sda_t'event then
        if now - t_sclev < T_SCL / 8 then
          fail("SDA change " & time'image(now - t_sclev) & " after an SCL edge");
        end if;
        t_sdaev := now;
      end if;
    end if;
  end process;

  -- ---------------------------------------------------------------- tx_en, done
  txen_mon : process
  begin
    loop
      wait until rising_edge(tx_en) or rising_edge(done);
      if done = '1' then
        if lol /= '0' then
          fail("done with LOL high");
        end if;
        if not ical_seen or now - (t_ical + 8 ms) < C_STABLE_MS * T_MS then
          fail("done " & time'image(now - (t_ical + 8 ms)) & " after the final LOL fall");
        end if;
        if tx_en /= '1' then
          fail("done with tx_en low");
        end if;
        exit;
      elsif not G_TX_EN_FIRST and dp_writes /= 5 then
        fail("tx_en high after " & integer'image(dp_writes) & " DP159 writes");
      end if;
    end loop;
    wait;
  end process;

  -- ---------------------------------------------------------------- main
  main : process
    variable ok_trace : boolean;
    variable expect_done : boolean;
    variable exp_cause   : std_logic_vector(3 downto 0);
    variable exp_lines   : std_logic_vector(1 downto 0);
    variable s0 : natural;
  begin
    rst <= '1';
    wait for 10 * T_CLK;
    wait until rising_edge(clk);
    rst <= '0';
    t_rst_rel <= now;

    wait until done = '1' or err = '1' for 3 sec;
    -- scl_stuck: every attempt ends with the first command (the stretch
    -- timeout fails it at once, the sequencer must not go on with the next
    -- byte of the transaction)
    if is_case("scl_stuck") and now - t_rst_rel >
       ((C_RETRIES + 1) * (C_RST_LOW_MS + C_RST_WAIT_MS + C_STRETCH_MS) + C_RETRIES * C_PAUSE_MS + 1) * T_MS then
      fail("err only after " & time'image(now - t_rst_rel) & " (stretch timeout not taken as failure?)");
    end if;
    s0 := starts;
    wait for 20 ms;
    if starts /= s0 then
      fail("bus activity after done/err");
    end if;
    if bus_busy or sda /= '1' or (scl /= '1' and not is_case("scl_stuck")) then
      fail("bus not idle at the end (no STOP)");
    end if;

    expect_done := is_case("normal") or is_case("nack_first") or is_case("stretch");
    if expect_done then
      if done /= '1' or err /= '0' then
        fail("expected done, got done=" & std_logic'image(done) & " err=" & std_logic'image(err));
      end if;
      if tx_en /= '1' then
        fail("tx_en low at the end");
      end if;
    else
      if err /= '1' or done /= '0' then
        fail("expected err, got done=" & std_logic'image(done) & " err=" & std_logic'image(err));
      end if;
    end if;

    -- attempts
    if is_case("normal") or is_case("stretch") then
      if attempts /= 1 then
        fail(integer'image(attempts) & " attempts, expected 1");
      end if;
    elsif is_case("nack_first") then
      if attempts /= 2 then
        fail(integer'image(attempts) & " attempts, expected 2");
      end if;
    else
      if attempts /= C_RETRIES + 1 then
        fail(integer'image(attempts) & " attempts, expected " & integer'image(C_RETRIES + 1));
      end if;
    end if;

    -- bus trace of the last attempt
    if expect_done or is_case("lol_stuck") then
      ok_trace := log_n = C_EXPECT'length;
      if not ok_trace then
        fail("trace has " & integer'image(log_n) & " entries, expected " & integer'image(C_EXPECT'length));
      end if;
      for i in 0 to C_EXPECT'length - 1 loop
        exit when i >= log_n;
        if log_v(i) /= C_EXPECT(i) then
          fail("trace " & integer'image(i) & ": " & log_v(i).kind & " 0x" & hex(log_v(i).dev) & " reg 0x" &
               hex(log_v(i).reg) & " = 0x" & hex(log_v(i).val) & ", expected " & C_EXPECT(i).kind & " 0x" &
               hex(C_EXPECT(i).dev) & " reg 0x" & hex(C_EXPECT(i).reg) & " = 0x" & hex(C_EXPECT(i).val));
        end if;
      end loop;
      if periods < 500 then
        fail("only " & integer'image(periods) & " SCL periods measured");
      end if;
    end if;
    if is_case("bad_id") and dp_writes_all /= 0 then
      fail(integer'image(dp_writes_all) & " DP159 writes despite the wrong ID");
    end if;
    if is_case("nack_always") and log_n /= 0 then
      fail("register accesses without an ACK");
    end if;
    -- diag: cause of the last failed attempt (kept after a later success), lines now
    if is_case("nack_always") or is_case("nack_first") then
      exp_cause := "0010";
    elsif is_case("bad_id") then
      exp_cause := "0100";
    elsif is_case("lol_stuck") then
      exp_cause := "1000";
    elsif is_case("scl_stuck") then
      exp_cause := "0001";
    else
      exp_cause := "0000";
    end if;
    if diag(3 downto 0) /= exp_cause then
      fail("diag cause " & to_string(diag(3 downto 0)) & ", expected " & to_string(exp_cause));
    end if;
    if is_case("scl_stuck") then
      exp_lines := "10";
    else
      exp_lines := "11";
    end if;
    -- the Si5324 never answers: the address byte (step 1) fails
    if is_case("nack_always") and diag(8 downto 6) /= "001" then
      fail("diag step " & to_string(diag(8 downto 6)) & ", expected 001 (address)");
    end if;
    wait for 100 ns;                                   -- two synchronizer stages
    if diag(5 downto 4) /= exp_lines then
      fail("diag SDA/SCL " & to_string(diag(5 downto 4)) & ", expected " & to_string(exp_lines));
    end if;

    report "attempts " & integer'image(attempts) & ", trace entries " & integer'image(log_n) &
           ", SCL periods checked " & integer'image(periods) & ", status 0x" & hex(status(15 downto 8)) &
           hex(status(7 downto 0)) severity note;
    if errors = 0 then
      report "zcu106_hdmi_ctl_tb " & G_CASE & ": PASS" severity note;
    else
      report "zcu106_hdmi_ctl_tb " & G_CASE & ": FAIL (" & integer'image(errors) & " errors)" severity note;
    end if;
    running <= false;
    wait;
  end process;

end architecture sim;
